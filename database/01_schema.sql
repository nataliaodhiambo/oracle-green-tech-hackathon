-- ------------------------------------------------------------
-- CORE TABLES
-- ------------------------------------------------------------
CREATE TABLE farmers (
    farmer_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    farmer_code  VARCHAR2(30)  NOT NULL UNIQUE,
    full_name    VARCHAR2(120) NOT NULL,
    phone_number VARCHAR2(30),
    county       VARCHAR2(80)  NOT NULL,
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE farm_plots (
    plot_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    plot_code     VARCHAR2(40) NOT NULL UNIQUE,
    farmer_id     NUMBER NOT NULL REFERENCES farmers(farmer_id),
    county        VARCHAR2(80) NOT NULL,
    latitude      NUMBER(10,7) NOT NULL,
    longitude     NUMBER(10,7) NOT NULL,
    area_hectares NUMBER(10,2) NOT NULL,
    created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_plot_lat  CHECK (latitude  BETWEEN -90 AND 90),
    CONSTRAINT ck_plot_lon  CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_plot_area CHECK (area_hectares > 0)
);

CREATE TABLE climate_scores (
    score_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    plot_id         NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    assessment_date DATE   NOT NULL,
    is_forecast     NUMBER(1) DEFAULT 0 NOT NULL,   -- 0 = observed, 1 = modelled/future row
    crs             NUMBER(5,2) NOT NULL,           -- crs_score
    forecasted_crs  NUMBER(5,2),
    ndvi            NUMBER(6,4),
    rainfall_pct    NUMBER(8,2),
    temp_stress     NUMBER(6,4),
    drought_risk    NUMBER(6,4),
    flood_index     NUMBER(6,4),                    -- optional, may be NULL
    data_source     VARCHAR2(40) DEFAULT 'ROLE1_IMPORT' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_cs_forecast  CHECK (is_forecast IN (0,1)),
    CONSTRAINT ck_cs_crs       CHECK (crs BETWEEN 0 AND 100),
    CONSTRAINT ck_cs_fcrs      CHECK (forecasted_crs IS NULL OR forecasted_crs BETWEEN 0 AND 100),
    CONSTRAINT ck_cs_ndvi      CHECK (ndvi IS NULL OR ndvi BETWEEN -1 AND 1),
    CONSTRAINT ck_cs_rain      CHECK (rainfall_pct IS NULL OR rainfall_pct >= 0),
    CONSTRAINT ck_cs_temp      CHECK (temp_stress IS NULL OR temp_stress BETWEEN 0 AND 1),
    CONSTRAINT ck_cs_drought   CHECK (drought_risk IS NULL OR drought_risk BETWEEN 0 AND 1),
    CONSTRAINT ck_cs_flood     CHECK (flood_index IS NULL OR flood_index BETWEEN 0 AND 1),
    CONSTRAINT uq_cs_plot_date UNIQUE (plot_id, assessment_date, is_forecast)
);

CREATE TABLE loans (
    loan_id                   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    loan_code                 VARCHAR2(40) NOT NULL UNIQUE,
    farmer_id                 NUMBER NOT NULL REFERENCES farmers(farmer_id),
    plot_id                   NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    score_id                  NUMBER REFERENCES climate_scores(score_id),
    pricing_crs               NUMBER(5,2),          -- snapshot of the CRS used to price
    principal_amount          NUMBER(14,2) NOT NULL,
    annual_interest_rate      NUMBER(5,2),          -- NULL while status = REVIEW
    term_months               NUMBER(4) DEFAULT 12 NOT NULL,
    estimated_total_interest  NUMBER(14,2),
    estimated_total_repayment NUMBER(14,2),
    status                    VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_loan_principal CHECK (principal_amount > 0),
    CONSTRAINT ck_loan_rate      CHECK (annual_interest_rate IS NULL OR annual_interest_rate BETWEEN 0 AND 100),
    CONSTRAINT ck_loan_term      CHECK (term_months BETWEEN 1 AND 120),
    CONSTRAINT ck_loan_status    CHECK (status IN ('PENDING','REVIEW','APPROVED','ACTIVE','REPAID','DECLINED'))
);

CREATE TABLE climate_events (
    event_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_code      VARCHAR2(50) NOT NULL UNIQUE,
    county          VARCHAR2(80) NOT NULL,
    event_type      VARCHAR2(20) NOT NULL,
    observed_date   DATE NOT NULL,
    index_value     NUMBER(10,4) NOT NULL,   -- 0..1, higher = more severe
    threshold_value NUMBER(10,4) NOT NULL,   -- trigger point (payout starts)
    extreme_value   NUMBER(10,4) NOT NULL,   -- full-payout point
    description     VARCHAR2(400),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_event_type    CHECK (event_type IN ('DROUGHT','FLOOD')),
    CONSTRAINT ck_event_values  CHECK (index_value >= 0 AND threshold_value >= 0
                                       AND extreme_value >= threshold_value)
);

CREATE TABLE payouts (
    payout_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    payout_code   VARCHAR2(80) NOT NULL UNIQUE,
    event_id      NUMBER NOT NULL REFERENCES climate_events(event_id),
    plot_id       NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    loan_id       NUMBER NOT NULL REFERENCES loans(loan_id),   -- no loan = no payout
    payout_amount NUMBER(14,2) NOT NULL,
    status        VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    triggered_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    paid_at       TIMESTAMP,
    CONSTRAINT ck_payout_amount CHECK (payout_amount > 0),
    CONSTRAINT ck_payout_status CHECK (status IN ('PENDING','APPROVED','PAID','REJECTED')),
    CONSTRAINT uq_event_plot    UNIQUE (event_id, plot_id)
);

CREATE TABLE kp_audit_log (
    audit_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    entity      VARCHAR2(20) NOT NULL,
    entity_code VARCHAR2(80) NOT NULL,
    old_status  VARCHAR2(20),
    new_status  VARCHAR2(20) NOT NULL,
    changed_by  VARCHAR2(128) DEFAULT USER,
    changed_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- ------------------------------------------------------------
-- STAGING for Role 1's JSON (never insert straight into core tables)
-- ------------------------------------------------------------
CREATE TABLE stg_role1_json (
    load_id   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    loaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    payload   CLOB NOT NULL CONSTRAINT ck_stg_json CHECK (payload IS JSON)
);

CREATE TABLE stg_role1_rows (
    load_id         NUMBER NOT NULL REFERENCES stg_role1_json(load_id) ON DELETE CASCADE,
    row_num         NUMBER NOT NULL,
    plot_code       VARCHAR2(40),
    farmer_code     VARCHAR2(30),
    farmer_name     VARCHAR2(120),
    county          VARCHAR2(80),
    latitude        NUMBER,
    longitude       NUMBER,
    area_hectares   NUMBER,
    assessment_date DATE,
    is_forecast_txt VARCHAR2(5),
    ndvi            NUMBER,
    rainfall_pct    NUMBER,
    temp_stress     NUMBER,
    drought_risk    NUMBER,
    flood_index     NUMBER,
    crs_score       NUMBER,
    forecasted_crs  NUMBER,
    reject_reason   VARCHAR2(40),
    PRIMARY KEY (load_id, row_num)
);

-- ------------------------------------------------------------
-- INDEXES
-- ------------------------------------------------------------
CREATE INDEX ix_plots_farmer      ON farm_plots(farmer_id);
CREATE INDEX ix_plots_county      ON farm_plots(county);
CREATE INDEX ix_scores_plot_date  ON climate_scores(plot_id, is_forecast, assessment_date);
CREATE INDEX ix_loans_plot_status ON loans(plot_id, status);
CREATE INDEX ix_events_county     ON climate_events(county, observed_date);
CREATE INDEX ix_payouts_status    ON payouts(status);

-- ------------------------------------------------------------
-- COLUMN COMMENTS = the data contract, inside the database
-- ------------------------------------------------------------
COMMENT ON COLUMN climate_scores.crs            IS '0-100. HIGHER = MORE RESILIENT (better). Role 1 field crs_score.';
COMMENT ON COLUMN climate_scores.forecasted_crs IS '0-100. HIGHER = better. Projected CRS for the next assessment period.';
COMMENT ON COLUMN climate_scores.ndvi           IS '-1..1. HIGHER = healthier vegetation (better).';
COMMENT ON COLUMN climate_scores.rainfall_pct   IS '% of long-term average for the period. 100 = normal; <100 = deficit (drought side); well above 100 = flood side.';
COMMENT ON COLUMN climate_scores.temp_stress    IS '0..1 normalised heat stress. HIGHER = WORSE.';
COMMENT ON COLUMN climate_scores.drought_risk   IS '0..1 probability-style drought severity. HIGHER = WORSE. Drives DROUGHT payouts.';
COMMENT ON COLUMN climate_scores.flood_index    IS '0..1 flood severity. HIGHER = WORSE. Optional. Drives FLOOD payouts.';
COMMENT ON COLUMN climate_scores.is_forecast    IS '0 = observed row, 1 = modelled/future row. Only 0 is used as "current".';

COMMIT;
