CREATE TABLE farmers (
    farmer_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    farmer_code     VARCHAR2(30) NOT NULL UNIQUE,
    full_name       VARCHAR2(120) NOT NULL,
    phone_number    VARCHAR2(30),
    county          VARCHAR2(80) DEFAULT 'Kajiado' NOT NULL,
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE farm_plots (
    plot_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    plot_code        VARCHAR2(40) NOT NULL UNIQUE,
    farmer_id        NUMBER NOT NULL REFERENCES farmers(farmer_id),
    plot_name        VARCHAR2(120),
    county           VARCHAR2(80) DEFAULT 'Kajiado' NOT NULL,
    latitude         NUMBER(10,7) NOT NULL,
    longitude        NUMBER(10,7) NOT NULL,
    area_hectares    NUMBER(10,2) DEFAULT 1 NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_plot_lat CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_plot_lon CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_plot_area CHECK (area_hectares > 0)
);

CREATE TABLE climate_scores (
    score_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    plot_id           NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    assessment_date   DATE NOT NULL,
    crs               NUMBER(5,2) NOT NULL,
    ndvi              NUMBER(6,4),
    drought_index     NUMBER(8,4),
    rainfall_deficit  NUMBER(8,4),
    land_surface_temp NUMBER(7,2),
    flood_index       NUMBER(8,4),
    data_source       VARCHAR2(40) DEFAULT 'ROLE1_IMPORT' NOT NULL,
    notes             VARCHAR2(400),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_crs_range CHECK (crs BETWEEN 0 AND 100),
    CONSTRAINT ck_ndvi_range CHECK (ndvi IS NULL OR ndvi BETWEEN -1 AND 1),
    CONSTRAINT uq_plot_assessment UNIQUE (plot_id, assessment_date)
);

CREATE TABLE loans (
    loan_id                 NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    loan_code               VARCHAR2(40) NOT NULL UNIQUE,
    farmer_id               NUMBER NOT NULL REFERENCES farmers(farmer_id),
    plot_id                 NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    score_id                NUMBER REFERENCES climate_scores(score_id),
    principal_amount        NUMBER(14,2) NOT NULL,
    annual_interest_rate    NUMBER(5,2) NOT NULL,
    term_months             NUMBER(4) DEFAULT 12 NOT NULL,
    estimated_total_interest NUMBER(14,2) NOT NULL,
    estimated_total_repayment NUMBER(14,2) NOT NULL,
    status                  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    created_at              TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_loan_principal CHECK (principal_amount > 0),
    CONSTRAINT ck_loan_rate CHECK (annual_interest_rate BETWEEN 0 AND 100),
    CONSTRAINT ck_loan_term CHECK (term_months BETWEEN 1 AND 120),
    CONSTRAINT ck_loan_status CHECK (status IN ('PENDING','APPROVED','ACTIVE','REPAID','DECLINED'))
);

CREATE TABLE climate_events (
    event_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    event_code        VARCHAR2(50) NOT NULL UNIQUE,
    county            VARCHAR2(80) NOT NULL,
    event_type        VARCHAR2(20) NOT NULL,
    observed_date     DATE NOT NULL,
    index_value       NUMBER(10,4) NOT NULL,
    threshold_value   NUMBER(10,4) NOT NULL,
    description       VARCHAR2(400),
    created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_event_type CHECK (event_type IN ('DROUGHT','FLOOD')),
    CONSTRAINT ck_event_index_nonnegative CHECK (index_value >= 0),
    CONSTRAINT ck_event_threshold_nonnegative CHECK (threshold_value >= 0)
);

CREATE TABLE payouts (
    payout_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    payout_code       VARCHAR2(60) NOT NULL UNIQUE,
    event_id          NUMBER NOT NULL REFERENCES climate_events(event_id),
    plot_id           NUMBER NOT NULL REFERENCES farm_plots(plot_id),
    loan_id           NUMBER REFERENCES loans(loan_id),
    payout_amount     NUMBER(14,2) NOT NULL,
    status            VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    triggered_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    paid_at           TIMESTAMP,
    CONSTRAINT ck_payout_amount CHECK (payout_amount > 0),
    CONSTRAINT ck_payout_status CHECK (status IN ('PENDING','APPROVED','PAID','REJECTED')),
    CONSTRAINT uq_event_plot UNIQUE (event_id, plot_id)
);

CREATE INDEX ix_plots_farmer ON farm_plots(farmer_id);
CREATE INDEX ix_scores_plot_date ON climate_scores(plot_id, assessment_date);
CREATE INDEX ix_loans_plot_status ON loans(plot_id, status);
CREATE INDEX ix_events_county_date ON climate_events(county, observed_date);
CREATE INDEX ix_payouts_status ON payouts(status);

-- ============================================================
-- 2. LOAN PRICING FUNCTION
-- CRS pricing is illustrative demo logic, not financial advice.
-- CRS >= 80 => 8%; 60-79.99 => 10%; 40-59.99 => 12%;
-- below 40 => NULL (manual review required).
-- ============================================================

CREATE OR REPLACE FUNCTION kp_interest_rate(p_crs IN NUMBER)
RETURN NUMBER
IS
BEGIN
    IF p_crs IS NULL OR p_crs < 0 OR p_crs > 100 THEN
        RAISE_APPLICATION_ERROR(-20001, 'CRS must be between 0 and 100.');
    ELSIF p_crs >= 80 THEN
        RETURN 8;
    ELSIF p_crs >= 60 THEN
        RETURN 10;
    ELSIF p_crs >= 40 THEN
        RETURN 12;
    ELSE
        RETURN NULL;
    END IF;
END;
/

-- ============================================================
-- 3. LOAN CREATION PROCEDURE
-- Uses simple flat interest for easy demo explanation:
-- interest = principal * annual rate * term_months / 1200.
-- ============================================================

CREATE OR REPLACE PROCEDURE kp_create_loan(
    p_loan_code IN VARCHAR2,
    p_farmer_id IN NUMBER,
    p_plot_id IN NUMBER,
    p_principal IN NUMBER,
    p_term_months IN NUMBER DEFAULT 12
)
IS
    v_score_id  climate_scores.score_id%TYPE;
    v_crs       climate_scores.crs%TYPE;
    v_rate      NUMBER;
    v_interest  NUMBER(14,2);
    v_total     NUMBER(14,2);
    v_owner     farm_plots.farmer_id%TYPE;
BEGIN
    IF p_principal IS NULL OR p_principal <= 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Principal must be greater than zero.');
    END IF;
    IF p_term_months IS NULL OR p_term_months < 1 OR p_term_months > 120 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Term must be between 1 and 120 months.');
    END IF;

    SELECT farmer_id INTO v_owner
      FROM farm_plots
     WHERE plot_id = p_plot_id;

    IF v_owner <> p_farmer_id THEN
        RAISE_APPLICATION_ERROR(-20004, 'The selected plot does not belong to this farmer.');
    END IF;

    SELECT score_id, crs INTO v_score_id, v_crs
      FROM (
          SELECT score_id, crs
            FROM climate_scores
           WHERE plot_id = p_plot_id
           ORDER BY assessment_date DESC, score_id DESC
      )
     WHERE ROWNUM = 1;

    v_rate := kp_interest_rate(v_crs);
    IF v_rate IS NULL THEN
        RAISE_APPLICATION_ERROR(-20005, 'CRS below 40: manual review required; no automatic offer.');
    END IF;

    v_interest := ROUND(p_principal * (v_rate / 100) * (p_term_months / 12), 2);
    v_total := p_principal + v_interest;

    INSERT INTO loans (
        loan_code, farmer_id, plot_id, score_id, principal_amount,
        annual_interest_rate, term_months, estimated_total_interest,
        estimated_total_repayment, status
    ) VALUES (
        p_loan_code, p_farmer_id, p_plot_id, v_score_id, p_principal,
        v_rate, p_term_months, v_interest, v_total, 'PENDING'
    );
END;
/

-- ============================================================
-- 4. PAYOUT TRIGGER PROCEDURE
-- Trigger semantics for this demo:
--   DROUGHT: event index_value >= threshold_value
--   FLOOD:   event index_value >= threshold_value
-- The index must be pre-normalized so higher means more severe.
-- One payout per (event_id, plot_id) is enforced by a unique key.
-- The event county is used as a simple geo-fence.
-- ============================================================

CREATE OR REPLACE PROCEDURE kp_trigger_payouts(
    p_event_code IN VARCHAR2,
    p_payout_amount IN NUMBER DEFAULT 5000
)
IS
    v_event_id     climate_events.event_id%TYPE;
    v_county       climate_events.county%TYPE;
    v_event_type   climate_events.event_type%TYPE;
    v_index        climate_events.index_value%TYPE;
    v_threshold    climate_events.threshold_value%TYPE;
    v_observed     climate_events.observed_date%TYPE;
BEGIN
    IF p_payout_amount IS NULL OR p_payout_amount <= 0 THEN
        RAISE_APPLICATION_ERROR(-20006, 'Payout amount must be greater than zero.');
    END IF;

    SELECT event_id, county, event_type, index_value, threshold_value, observed_date
      INTO v_event_id, v_county, v_event_type, v_index, v_threshold, v_observed
      FROM climate_events
     WHERE event_code = p_event_code;

    IF v_index < v_threshold THEN
        RAISE_APPLICATION_ERROR(-20007, 'Climate trigger threshold not reached; no payouts created.');
    END IF;

    INSERT INTO payouts (
        payout_code, event_id, plot_id, loan_id, payout_amount, status
    )
    SELECT
        'KP-' || p_event_code || '-' || TO_CHAR(fp.plot_id),
        v_event_id,
        fp.plot_id,
        (SELECT MAX(l.loan_id)
           FROM loans l
          WHERE l.plot_id = fp.plot_id
            AND l.status IN ('APPROVED','ACTIVE')),
        p_payout_amount,
        'PENDING'
      FROM farm_plots fp
     WHERE UPPER(fp.county) = UPPER(v_county)
       AND NOT EXISTS (
           SELECT 1
             FROM payouts p
            WHERE p.event_id = v_event_id
              AND p.plot_id = fp.plot_id
       );

    -- If no matching plots exist, the procedure completes without inserts.
END;
/

