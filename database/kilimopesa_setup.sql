CREATE OR REPLACE VIEW v_farm_risk_latest AS
SELECT
    fp.plot_id,
    fp.plot_code,
    fp.plot_name,
    fp.county,
    fp.latitude,
    fp.longitude,
    fp.area_hectares,
    f.farmer_id,
    f.farmer_code,
    f.full_name AS farmer_name,
    cs.score_id,
    cs.assessment_date,
    cs.crs,
    cs.ndvi,
    cs.drought_index,
    cs.rainfall_deficit,
    cs.land_surface_temp,
    cs.flood_index,
    CASE
        WHEN cs.crs >= 80 THEN 'RESILIENT'
        WHEN cs.crs >= 60 THEN 'MODERATE'
        WHEN cs.crs >= 40 THEN 'VULNERABLE'
        ELSE 'HIGH RISK'
    END AS risk_band
FROM farm_plots fp
JOIN farmers f ON f.farmer_id = fp.farmer_id
LEFT JOIN (
    SELECT cs1.*,
           ROW_NUMBER() OVER (
               PARTITION BY cs1.plot_id
               ORDER BY cs1.assessment_date DESC, cs1.score_id DESC
           ) AS rn
      FROM climate_scores cs1
) cs ON cs.plot_id = fp.plot_id AND cs.rn = 1;

CREATE OR REPLACE VIEW v_loan_portfolio AS
SELECT
    l.loan_id,
    l.loan_code,
    l.farmer_id,
    f.full_name AS farmer_name,
    l.plot_id,
    fp.plot_code,
    fp.county,
    l.score_id,
    cs.crs,
    l.principal_amount,
    l.annual_interest_rate,
    l.term_months,
    l.estimated_total_interest,
    l.estimated_total_repayment,
    l.status,
    l.created_at
FROM loans l
JOIN farmers f ON f.farmer_id = l.farmer_id
JOIN farm_plots fp ON fp.plot_id = l.plot_id
LEFT JOIN climate_scores cs ON cs.score_id = l.score_id;

CREATE OR REPLACE VIEW v_payout_events AS
SELECT
    p.payout_id,
    p.payout_code,
    ce.event_code,
    ce.event_type,
    ce.county,
    ce.observed_date,
    ce.index_value,
    ce.threshold_value,
    fp.plot_code,
    fp.plot_id,
    f.full_name AS farmer_name,
    p.loan_id,
    p.payout_amount,
    p.status,
    p.triggered_at,
    p.paid_at
FROM payouts p
JOIN climate_events ce ON ce.event_id = p.event_id
JOIN farm_plots fp ON fp.plot_id = p.plot_id
JOIN farmers f ON f.farmer_id = fp.farmer_id;

CREATE OR REPLACE VIEW v_kpi_summary AS
SELECT
    (SELECT COUNT(*) FROM farm_plots) AS total_plots,
    (SELECT ROUND(AVG(crs), 2)
       FROM (
           SELECT crs,
                  ROW_NUMBER() OVER (
                      PARTITION BY plot_id
                      ORDER BY assessment_date DESC, score_id DESC
                  ) rn
             FROM climate_scores
       )
      WHERE rn = 1) AS average_latest_crs,
    (SELECT COUNT(*)
       FROM loans
      WHERE status IN ('PENDING','APPROVED','ACTIVE')) AS active_or_pending_loans,
    (SELECT NVL(SUM(principal_amount),0)
       FROM loans
      WHERE status IN ('APPROVED','ACTIVE')) AS approved_loan_principal,
    (SELECT COUNT(*) FROM payouts WHERE status IN ('PENDING','APPROVED')) AS pending_payouts,
    (SELECT NVL(SUM(payout_amount),0)
       FROM payouts
      WHERE status IN ('PENDING','APPROVED')) AS pending_payout_amount
FROM dual;

